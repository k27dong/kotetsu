import importlib.metadata

import segno

WIFI_SETUP_HOTSPOT = "WIFI:T:nopass;S:kotetsu-setup;;"


def main() -> None:
    qr = segno.make(WIFI_SETUP_HOTSPOT, error="q", micro=False, boost_error=False)
    rows = [[int(bool(module)) for module in row] for row in qr.matrix]
    version = importlib.metadata.version("segno")
    print(f"// Generated by pi/tools/gen_wifi_qr.py from segno {version}. Do not edit.")
    print('#include "render/wifi_qr.h"')
    print()
    print("#include <stdint.h>")
    print()
    print(f"const int WIFI_QR_SIZE = {len(rows)};")
    print()
    print("const uint8_t WIFI_QR_MODULES[] = {")
    for row in rows:
        print("        " + ", ".join(str(module) for module in row) + ",")
    print("};")


if __name__ == "__main__":
    main()
